WEST_AFRICA_USERS = (
    "<p>Users from agriculture, water, health, disaster management and media communities "
    "are invited to the forum for exchanges, interactive discussions on the historical, "
    "current and expected climate conditions, related impacts, advices and recommendations "
    "to cope with negative impacts or increase benefits linked to possible opportunities "
    "due to favorable climate conditions.</p>"
    "<h2>Success stories based on feedback of users</h2>"
    "<p>In 2008, ACMAD issued an update of consensus prediction for the region with high "
    "probability ( up to 50%) for above average rainfall over much of the southern Sahel. "
    "Wet to very wet years in the region are usually associated with higher frequency of "
    "heavy rains and floods. The forecast was used for an appeal by Red Cross for funding "
    "for flood preparedness. The funds were granted leading to prepositioning of relief "
    "items (mosquito nets, blankets…). Without this forecast, items would have been "
    "provided after floods. The efforts would have then cost more in time and transport "
    "expenses. This was the first time in Red Cross’s history that based on seasonal "
    "forecasts, funds were requested and used to prepare for potential emergency. Wet "
    "years are also related to more mosquitoes and malaria in Sub Saharan Africa. UNICEF "
    "office in Niger used seasonal forecasts to prepare and preposition drugs and mosquito "
    "nets for vulnerable communities.</p>"
)

